# STEP 0: Build the three source files from the UCI dataset

uci_url <- "https://archive.ics.uci.edu/ml/machine-learning-databases/00352/Online%20Retail.xlsx"
raw_path <- "Online_Retail.xlsx"

if (!file.exists(raw_path)) {
  download.file(uci_url, raw_path, mode = "wb")
}

raw <- read_excel(raw_path, sheet = 1)
names(raw) <- trimws(names(raw))   # safety: strip stray whitespace in headers

# -- transactions.csv --
transactions_src <- raw %>%
  select(InvoiceNo, StockCode, CustomerID, Quantity, InvoiceDate)
write_csv(transactions_src, "transactions.csv")

# -- products.json (one row per StockCode, first Description/UnitPrice seen) --
products_src <- raw %>%
  select(StockCode, Description, UnitPrice) %>%
  distinct(StockCode, .keep_all = TRUE)
write_json(products_src, "products.json", auto_unbox = TRUE)

# -- customers.xlsx (one row per CustomerID) --
customers_src <- raw %>%
  select(CustomerID, Country) %>%
  filter(!is.na(CustomerID)) %>%
  distinct(CustomerID, .keep_all = TRUE)
write_xlsx(customers_src, "customers.xlsx")

#############################################################
# TASK 1: Import and Clean the Data
#############################################################

transactions <- read_csv("transactions.csv", show_col_types = FALSE)
products     <- fromJSON("products.json")
customers    <- read_excel("customers.xlsx")

# -- Inspect --
str(transactions)
str(products)
str(customers)

colSums(is.na(transactions))
colSums(is.na(products))
colSums(is.na(customers))

nrow(transactions)                          # before cleaning
sum(duplicated(transactions))               # duplicate rows present?

# -- Cleaning decisions --
# 1. Drop rows with missing CustomerID: customer-level analysis (Task 3)
#    is impossible without it, and ~25% of UCI rows are anonymous guest
#    checkouts we can't attribute to a customer.
# 2. Drop exact duplicate transaction rows.
# 3. Drop Quantity <= 0: negative/zero quantities are returns or
#    cancellations (UCI marks these with InvoiceNo starting with "C"),
#    not genuine sales, so they don't belong in a revenue analysis.
# 4. Drop UnitPrice <= 0: these are data-entry artifacts (e.g. "free"
#    adjustment postings) with no real revenue meaning.

transactions_clean <- transactions %>%
  filter(!is.na(CustomerID)) %>%
  distinct() %>%
  filter(Quantity > 0) %>%
  filter(!grepl("^C", InvoiceNo))            # belt-and-braces: drop cancellations

products_clean <- products %>%
  filter(!is.na(StockCode), !is.na(UnitPrice)) %>%
  filter(UnitPrice > 0) %>%
  distinct(StockCode, .keep_all = TRUE)

customers_clean <- customers %>%
  filter(!is.na(CustomerID), !is.na(Country)) %>%
  distinct(CustomerID, .keep_all = TRUE)

nrow(transactions_clean)                     # after cleaning
sum(duplicated(transactions_clean))

# Revenue is created AFTER the join in Task 2, since UnitPrice lives
# in the products table, not in transactions.

#############################################################
# TASK 2: Integrate the Multiple Data Sources
#############################################################

# left_join transactions -> products: we want to KEEP every cleaned
# transaction even if a StockCode is missing from the product master
# (lets us measure data-quality gaps instead of silently losing sales).
integrated <- transactions_clean %>%
  left_join(products_clean, by = "StockCode")

# inner_join -> customers: a transaction is only usable for the
# customer/country analysis in Task 3 if we can identify who made it
# and where, so unmatched customers are dropped here deliberately.
integrated <- integrated %>%
  inner_join(customers_clean, by = "CustomerID")

integrated <- integrated %>%
  filter(!is.na(UnitPrice)) %>%              # drop rows with no product match
  mutate(Revenue = Quantity * UnitPrice)

# -- Verify dimensions --
dim(transactions_clean)
dim(integrated)

# -- Unmatched records --
unmatched_products <- transactions_clean %>% anti_join(products_clean, by = "StockCode")
unmatched_customers <- transactions_clean %>% anti_join(customers_clean, by = "CustomerID")
nrow(unmatched_products)
nrow(unmatched_customers)

# Join justification: left_join on products preserves transaction volume
# for auditing data-quality gaps; inner_join on customers is deliberate
# because Task 3's customer/country metrics are meaningless without a
# resolved CustomerID + Country.

#############################################################
# TASK 3: Sales and Customer Analysis
#############################################################

# 1. Total sales revenue
total_revenue <- sum(integrated$Revenue)
total_revenue

# 2. Top 5 products by revenue
top5_products <- integrated %>%
  group_by(StockCode, Description) %>%
  summarise(ProductRevenue = sum(Revenue), .groups = "drop") %>%
  arrange(desc(ProductRevenue)) %>%
  slice_head(n = 5)
top5_products

# 3. Top 5 countries by revenue
top5_countries <- integrated %>%
  group_by(Country) %>%
  summarise(CountryRevenue = sum(Revenue), .groups = "drop") %>%
  arrange(desc(CountryRevenue)) %>%
  slice_head(n = 5)
top5_countries

# 4. Top 5 customers by total purchase value
top5_customers <- integrated %>%
  group_by(CustomerID) %>%
  summarise(CustomerRevenue = sum(Revenue), .groups = "drop") %>%
  arrange(desc(CustomerRevenue)) %>%
  slice_head(n = 5)
top5_customers

# -- Customer value segmentation --
customer_value <- integrated %>%
  group_by(CustomerID) %>%
  summarise(TotalSpend = sum(Revenue), .groups = "drop")

# Data-driven thresholds from the customer spend distribution itself
q <- quantile(customer_value$TotalSpend, probs = c(0.5, 0.8, 0.95))

customer_value <- customer_value %>%
  mutate(ValueSegment = case_when(
    TotalSpend < q[1]  ~ "Low Value",
    TotalSpend < q[2]  ~ "Medium Value",
    TotalSpend < q[3]  ~ "High Value",
    TRUE               ~ "Premium"
  ))

table(customer_value$ValueSegment)

# -- High-performing vs underperforming market --
top5_countries          # highest revenue country = top-performing market
bottom_countries <- integrated %>%
  group_by(Country) %>%
  summarise(CountryRevenue = sum(Revenue), .groups = "drop") %>%
  arrange(CountryRevenue) %>%
  slice_head(n = 5)
bottom_countries         # lowest revenue country = underperforming market

