#############################################################
# TASK 4: Store and Retrieve Data Using SQL
#############################################################

con <- dbConnect(RSQLite::SQLite(), "retail_sales.db")

final_data <- integrated %>%
  left_join(customer_value %>% select(CustomerID, ValueSegment),
            by = "CustomerID")

dbWriteTable(con, "retail_sales", final_data, overwrite = TRUE)

# Query 1: Top 5 customers based on revenue
q1 <- dbGetQuery(con, "
  SELECT CustomerID, SUM(Revenue) AS TotalRevenue
  FROM retail_sales
  GROUP BY CustomerID
  ORDER BY TotalRevenue DESC
  LIMIT 5;
")
q1

# Query 2: Total revenue by country
q2 <- dbGetQuery(con, "
  SELECT Country, SUM(Revenue) AS TotalRevenue
  FROM retail_sales
  GROUP BY Country
  ORDER BY TotalRevenue DESC;
")
q2

dbDisconnect(con)

